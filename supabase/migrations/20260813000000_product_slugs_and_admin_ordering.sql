-- Two admin correctness fixes that need the database: the product slug, and
-- the ordering of brands and categories.
--
-- ---------------------------------------------------------------------------
-- 1. PRODUCT SLUGS
--
-- `products.slug` is the whole of a product's URL (/product/:slug) and it is
-- UNIQUE. The admin generated it with
--   name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
-- which keeps nothing but ASCII. This store is Arabic first (index.html is
-- lang="ar" dir="rtl") and every product it sells is named in Arabic, so that
-- expression returned the empty string for every product the owner has ever
-- added: the first one saved with an unroutable empty slug and the second hit
-- this unique constraint with a raw Postgres message.
--
-- What the LIVE table actually holds, read before writing this migration:
--
--   118 products
--     1 with a clean Latin slug         ('lv')
--    90 with a single emoji or symbol   ('🐮', '😀', '⚽️', '🐻‍❄️' ...)
--    27 with a single Arabic letter     ('ء', 'ق', 'ش' ...)
--     0 empty
--     0 duplicated, even case insensitively
--     0 with leading or trailing whitespace
--
-- So the owner never met the crash. They found a workaround and have been
-- typing one arbitrary unique character into the slug box for all 118
-- products, the same habit that produced the corrupted brand key 'ل'.
--
-- The generator is fixed in src/lib/slug.ts, which keeps Arabic instead of
-- erasing it, and numbers a duplicate before writing rather than letting the
-- constraint raise. New and edited products need nothing from this migration.
--
-- REWRITING THE 117 EXISTING SLUGS IS NOT DONE HERE, DELIBERATELY. Those are
-- 117 live URLs: bookmarks, WhatsApp and Instagram links, anything indexed.
-- Changing them is the owner's decision and it has been put to them. Section 1c
-- below is the repair, written and ready, commented out. Enable it only on the
-- owner's answer, and read the trade-off in the report before you do.
-- ---------------------------------------------------------------------------

-- 1a. Say what is in the table now, so the next person does not have to go and
--     look. Read only.
do $$
declare
  v_total int;
  v_blank int;
  v_odd int;
  v_dupes int;
begin
  select
    count(*),
    -- The exact NEGATION of the products_slug_not_blank CHECK added below.
    -- Keep the two in step.
    count(*) filter (where slug is null or slug <> btrim(slug) or slug = ''),
    -- Not a slug this store could have generated: anything outside ASCII
    -- alphanumerics, the Arabic block and the separating hyphen.
    count(*) filter (where slug !~ '^[a-z0-9؀-ۿ]+(-[a-z0-9؀-ۿ]+)*$')
  into v_total, v_blank, v_odd
  from public.products;

  select count(*) into v_dupes
  from (select lower(slug) as s from public.products group by 1 having count(*) > 1) d;

  raise notice 'product slugs: % rows, % blank, % not machine generated, % duplicated',
    v_total, v_blank, v_odd, v_dupes;

  -- The CHECK below is added NOT VALID, so the ALTER succeeds whatever is in
  -- the table and a violating row would not be caught here at all. It would be
  -- caught much later and much worse: a NOT VALID check is still evaluated
  -- against the new row version of every future UPDATE of that row, and
  -- place_cod_order() and fulfill_order() both UPDATE products.stock. One
  -- blank or untrimmed slug would therefore freeze that product and fail every
  -- checkout that touches it, weeks after this migration was applied and with
  -- nothing pointing back at it. Stopping now is the cheap failure.
  if v_blank > 0 then
    raise exception 'product slugs: % row(s) have a blank or untrimmed slug. Fix them by hand (or enable section 1c) before adding the constraint', v_blank;
  end if;
end $$;

-- 1b. A blank slug is an unroutable product. The client can no longer produce
--     one, and this makes sure nothing else ever does either. NOT VALID
--     because the audit above has just shown there are no blanks to scan for,
--     so validating would only take a lock on a live table to learn that. It
--     still enforces every INSERT and UPDATE from here on.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'products_slug_not_blank'
      and conrelid = 'public.products'::regclass
  ) then
    alter table public.products
      add constraint products_slug_not_blank
      check (slug = btrim(slug) and slug <> '')
      not valid;
  end if;
end $$;


-- ---------------------------------------------------------------------------
-- 2. ORDERING BRANDS AND CATEGORIES
--
-- Moving a brand or a category up and down fired two independent UPDATEs that
-- traded positions, with both results discarded. A half applied swap leaves
-- the two rows sharing one position, and every later swap of that pair then
-- trades identical numbers: a button that silently does nothing, for good.
--
-- This is admin_reorder_positions() (20260812000000) for the two tables keyed
-- by a text `value` rather than a uuid `id`, and it is the same contract:
-- position becomes the index in the list the client sent, all of it or none.
-- ---------------------------------------------------------------------------
create or replace function public.admin_reorder_positions_by_value(p_table text, p_values text[])
returns integer
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_updated integer;
begin
  if not public.is_admin() then
    raise exception 'admin_reorder_positions_by_value: not authorised'
      using errcode = 'P0001', hint = 'not_admin';
  end if;

  if p_table is null or p_table not in ('brands', 'categories') then
    raise exception 'admin_reorder_positions_by_value: % is not reorderable', coalesce(p_table, '<null>')
      using errcode = 'P0001', hint = 'table_not_reorderable';
  end if;

  if p_values is null or array_length(p_values, 1) is null then
    return 0;
  end if;

  -- WITH ORDINALITY is the ordering: position becomes the index of the key in
  -- the array the client sent. 0 based, matching the rows the storefront
  -- already orders by.
  execute format($q$
    update public.%I t
    set "position" = v.ord - 1
    from (select val, ord from unnest($1::text[]) with ordinality as u(val, ord)) v
    where t.value = v.val
  $q$, p_table)
  using p_values;

  get diagnostics v_updated = row_count;

  -- Every key the caller sent must have matched a row. If one was deleted in
  -- another tab the survivors have just been renumbered around the gap, which
  -- is a DIFFERENT order from the one on screen, and a non-zero row count
  -- would read as success at the call site. Raising rolls the whole statement
  -- back, so the list is either fully applied or untouched.
  if v_updated <> array_length(p_values, 1) then
    raise exception 'admin_reorder_positions_by_value: % of % rows matched in %',
      v_updated, array_length(p_values, 1), p_table
      using errcode = 'P0001', hint = 'reorder_incomplete';
  end if;

  return v_updated;
end;
$$;

comment on function public.admin_reorder_positions_by_value(text, text[]) is
  'Rewrites position 0..n-1 across brands or categories in one statement, keyed by their text `value`. Raises (rolling the statement back) unless every key matched a row. Admin only. Sibling of admin_reorder_positions() for the uuid keyed tables.';

revoke execute on function public.admin_reorder_positions_by_value(text, text[]) from anon, public;
grant execute on function public.admin_reorder_positions_by_value(text, text[]) to authenticated;

-- The admin used to compute max(position) + 1 from the array loaded in the
-- browser, which could be hours old, so a brand added while another tab held
-- a stale list landed on a position another row already had.
--
-- This narrows that window to the gap between two inserts; it does NOT close
-- it. Under READ COMMITTED neither transaction can see the other's uncommitted
-- row, so two truly concurrent inserts still read the same maximum. The cost
-- of that is two rows sharing a position until the next reorder renumbers
-- them, which is not worth a unique index or an advisory lock.
--
-- ponytail: position 0 means "not specified", which is what the column default
-- gives when the client omits it. Nothing in the app inserts a deliberate 0
-- (a new row always goes last), and the reorder RPC above is the only other
-- writer of this column.
create or replace function public.assign_next_position()
returns trigger
language plpgsql
set search_path to 'public', 'pg_temp'
as $$
declare
  v_next int;
begin
  if new."position" is null or new."position" = 0 then
    execute format('select coalesce(max("position") + 1, 0) from public.%I', tg_table_name)
      into v_next;
    new."position" := v_next;
  end if;
  return new;
end;
$$;

comment on function public.assign_next_position() is
  'BEFORE INSERT on brands and categories: puts a new row last when no position was given (null, or the default 0), instead of trusting a maximum computed in the browser. Narrows but does not close the concurrent-insert race: two inserts in flight together still read the same maximum, and the next reorder renumbers them.';

drop trigger if exists brands_assign_next_position on public.brands;
create trigger brands_assign_next_position
  before insert on public.brands
  for each row execute function public.assign_next_position();

drop trigger if exists categories_assign_next_position on public.categories;
create trigger categories_assign_next_position
  before insert on public.categories
  for each row execute function public.assign_next_position();
